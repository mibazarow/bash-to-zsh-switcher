#!/bin/bash

# =============================================================================
# ZSH Config Tester для macOS
# =============================================================================
# Обертка для тестирования конфигурации zsh на macOS
# 
# Использование: ./test-macos.sh
# =============================================================================

set -e

# Определение цветов для вывода
GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}[INFO]${NC} Запуск тестирования конфигурации ZSH для macOS..."

# Проверка наличия директории
if [ ! -d "macos-switcher" ]; then
    echo -e "${BLUE}[ERROR]${NC} Директория macos-switcher не найдена!"
    echo "Убедитесь, что вы запускаете скрипт из корня проекта."
    exit 1
fi

# Запуск основного скрипта тестирования
./macos-switcher/test.sh

echo -e "${GREEN}[SUCCESS]${NC} Тестирование завершено!"
