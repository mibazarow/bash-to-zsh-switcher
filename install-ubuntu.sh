#!/bin/bash

# =============================================================================
# ZSH Switcher для Ubuntu/Debian
# =============================================================================
# Обертка для установки zsh с autosuggestions на Ubuntu/Debian
# 
# Использование: ./install-ubuntu.sh
# =============================================================================

set -e

# Определение цветов для вывода
GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}[INFO]${NC} Запуск установщика ZSH для Ubuntu/Debian..."

# Проверка наличия директории
if [ ! -d "ubuntu-switcher" ]; then
    echo -e "${BLUE}[ERROR]${NC} Директория ubuntu-switcher не найдена!"
    echo "Убедитесь, что вы запускаете скрипт из корня проекта."
    exit 1
fi

# Запуск основного скрипта установки
./ubuntu-switcher/install.sh

echo -e "${GREEN}[SUCCESS]${NC} Установка завершена!"
echo ""
echo "Для тестирования конфигурации выполните: ./test-ubuntu.sh"
echo "Для отката изменений выполните: ./uninstall-ubuntu.sh"
