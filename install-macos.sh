#!/bin/bash

# =============================================================================
# ZSH Switcher для macOS
# =============================================================================
# Обертка для установки zsh с autosuggestions на macOS
# 
# Использование: ./install-macos.sh
# =============================================================================

set -e

# Определение цветов для вывода
GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}[INFO]${NC} Запуск установщика ZSH для macOS..."

# Проверка наличия директории
if [ ! -d "macos-switcher" ]; then
    echo -e "${BLUE}[ERROR]${NC} Директория macos-switcher не найдена!"
    echo "Убедитесь, что вы запускаете скрипт из корня проекта."
    exit 1
fi

# Запуск основного скрипта установки
./macos-switcher/install.sh

echo -e "${GREEN}[SUCCESS]${NC} Установка завершена!"
echo ""
echo "Для тестирования конфигурации выполните: ./test-macos.sh"
echo "Для отката изменений выполните: ./uninstall-macos.sh"
