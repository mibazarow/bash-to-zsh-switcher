#!/bin/bash

# =============================================================================
# ZSH Uninstaller для Ubuntu/Debian
# =============================================================================
# Обертка для отката к bash на Ubuntu/Debian
# 
# Использование: ./uninstall-ubuntu.sh
# =============================================================================

set -e

# Определение цветов для вывода
GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}[INFO]${NC} Запуск скрипта отката для Ubuntu/Debian..."

# Проверка наличия директории
if [ ! -d "ubuntu-switcher" ]; then
    echo -e "${BLUE}[ERROR]${NC} Директория ubuntu-switcher не найдена!"
    echo "Убедитесь, что вы запускаете скрипт из корня проекта."
    exit 1
fi

# Запуск основного скрипта отката
./ubuntu-switcher/uninstall.sh

echo -e "${GREEN}[SUCCESS]${NC} Откат завершен!"
