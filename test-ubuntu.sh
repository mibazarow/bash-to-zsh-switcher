#!/bin/bash

# =============================================================================
# ZSH Config Tester для Ubuntu/Debian
# =============================================================================
# Обертка для тестирования конфигурации zsh на Ubuntu/Debian
# 
# Использование: ./test-ubuntu.sh
# =============================================================================

set -e

# Определение цветов для вывода
GREEN='\033[0;32m'
BLUE='\033[0;34m'
NC='\033[0m'

echo -e "${BLUE}[INFO]${NC} Запуск тестирования конфигурации ZSH для Ubuntu/Debian..."

# Проверка наличия директории
if [ ! -d "ubuntu-switcher" ]; then
    echo -e "${BLUE}[ERROR]${NC} Директория ubuntu-switcher не найдена!"
    echo "Убедитесь, что вы запускаете скрипт из корня проекта."
    exit 1
fi

# Запуск основного скрипта тестирования
./ubuntu-switcher/test.sh

echo -e "${GREEN}[SUCCESS]${NC} Тестирование завершено!"
